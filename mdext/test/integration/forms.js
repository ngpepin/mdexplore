'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vscode = require('vscode');
const {PreviewCoordinator} = require('../../src/previewCoordinator');
const {hash,parseFields,documentRevision} = require('../../src/formFields');
exports.run = async function() {
  const file = path.join(vscode.workspace.workspaceFolders[0].uri.fsPath,'integration-form-'+Date.now()+'.md');
  const source = '\uFEFF# Form\n\n<!-- mdform:field id="answer" -->____<!-- /mdform -->\n';
  fs.writeFileSync(file,source);
  const uri=vscode.Uri.file(file);
  const doc=await vscode.workspace.openTextDocument(uri);
  assert.equal(doc.getText().startsWith('\uFEFF'),false,'VS Code strips the BOM');
  const displayedRevision=await documentRevision(file,doc.getText());
  assert.equal(displayedRevision,hash(source));
  const messages=[];
  const surface={uri,formRevision:hash(source),webview:{postMessage:m=>messages.push(m)}};
  const save = message => PreviewCoordinator.prototype.saveFormField.call({},surface,message);
  await save({id:'answer',value:'Saved through real host',revision:hash(source),documentKey:uri.toString()});
  assert.equal(messages.pop().ok,true,'real VS Code host should accept clean local document');
  for(let i=0;i<100 && !doc.getText().includes('Saved through real host');i++) await new Promise(r=>setTimeout(r,100));
  assert.ok(doc.getText().includes('Saved through real host'),'VS Code watcher should reload the clean document');
  assert.equal(doc.isDirty,false);
  assert.equal(fs.readFileSync(file.replace('.md','.preedit.md'),'utf8'),source);
  const insertionSource=fs.readFileSync(file,'utf8');
  await save({operation:'insert',kind:'check',revision:hash(insertionSource),documentKey:uri.toString(),
    selection:{text:'Form',startLine:0,endLine:1,occurrence:0,occurrences:1}});
  assert.equal(messages.pop().ok,true,'real host should permit explicit insertion');
  for(let i=0;i<100 && !doc.getText().includes('[ ] Done');i++) await new Promise(r=>setTimeout(r,100));
  assert.ok(doc.getText().includes('[ ] Done'),'inserted checkbox should reload in source editor');
  assert.equal(fs.readFileSync(file.replace('.md','.preedit.md'),'utf8'),source);
  const edit=new vscode.WorkspaceEdit();
  edit.insert(uri,new vscode.Position(0,0),'Unsaved source\n');
  await vscode.workspace.applyEdit(edit);
  assert.equal(doc.isDirty,true);
  const disk=fs.readFileSync(file,'utf8');
  await save({id:'answer',value:'Must reject',revision:hash(disk),documentKey:uri.toString()});
  assert.match(messages.pop().error,/unsaved/);
  assert.equal(fs.readFileSync(file,'utf8'),disk);
  assert.equal(parseFields(disk).find(f=>f.id==='answer').value,'Saved through real host');
  await vscode.commands.executeCommand('workbench.action.files.revert');
  console.log('MDFORM REAL VSCODE HOST: PASS (disk write, insertion, backup, clean buffer reload, dirty rejection)');
};
